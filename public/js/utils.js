/**
 * Generate a short unique ID (collision-safe for our scale)
 */
export function generateId() {
  const ts = Date.now().toString(36);
  const rand = Math.random().toString(36).substring(2, 8);
  return `${ts}-${rand}`;
}

/**
 * Format bytes to human-readable string
 */
export function formatBytes(bytes) {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return `${(bytes / Math.pow(k, i)).toFixed(1)} ${sizes[i]}`;
}

/**
 * Format a date string for display
 */
export function formatDate(dateStr) {
  if (!dateStr) return 'Unknown date';
  try {
    const d = new Date(dateStr);
    return d.toLocaleDateString('en-NG', {
      year: 'numeric',
      month: 'short',
      day: 'numeric',
    });
  } catch {
    return dateStr;
  }
}

/**
 * Show a toast notification
 */
export function showToast(message, type = 'success', duration = 3500) {
  let container = document.querySelector('.toast-container');
  if (!container) {
    container = document.createElement('div');
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast ${type}`;
  toast.innerHTML = `
    <span>${type === 'success' ? '✓' : type === 'error' ? '✗' : '⚠'}</span>
    <span>${message}</span>
  `;
  container.appendChild(toast);

  setTimeout(() => {
    toast.classList.add('hiding');
    toast.addEventListener('animationend', () => toast.remove());
  }, duration);
}

/**
 * Debounce function calls
 */
export function debounce(fn, delay = 300) {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), delay);
  };
}

/**
 * Escape HTML to prevent XSS
 */
export function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}

/**
 * Check if browser supports WebP
 */
export async function supportsWebP() {
  if (typeof createImageBitmap === 'undefined') return false;
  const webpBlob = await fetch('data:image/webp;base64,UklGRh4AAABXRUJQVlA4TBEAAAAvAAAAAAfQ//73v/+BiTjt7REA')
    .then(r => r.blob())
    .catch(() => null);
  if (!webpBlob) return false;
  try {
    await createImageBitmap(webpBlob);
    return true;
  } catch {
    return false;
  }
}

/**
 * API fetch wrapper with error handling
 */
export async function apiFetch(path, options = {}) {
  const response = await fetch(path, {
    ...options,
    headers: {
      ...(options.headers || {}),
    },
  });

  if (!response.ok) {
    const errorText = await response.text().catch(() => 'Unknown error');
    throw new Error(`API Error (${response.status}): ${errorText}`);
  }

  const contentType = response.headers.get('content-type');
  if (contentType && contentType.includes('application/json')) {
    return response.json();
  }
  return response;
}

/**
 * Get / Set Admin Code in Session Storage
 */
export function getAdminCode() {
  return sessionStorage.getItem('refractories_admin') || localStorage.getItem('refractories_admin') || '';
}

export function setAdminCode(code, remember = true) {
  if (remember) {
    localStorage.setItem('refractories_admin', code);
  }
  sessionStorage.setItem('refractories_admin', code);
}

export function clearAdminCode() {
  sessionStorage.removeItem('refractories_admin');
  localStorage.removeItem('refractories_admin');
}

